    @SerialName("checksum") val checksum: String? = null,
    @SerialName("collection") val collection: Long? = null,
    @SerialName("collections") val collections: List<Long> = emptyList(),
    @SerialName("cover") val cover: Long? = null,
    @SerialName("created_at") val createdAt: Long? = null,
    @SerialName("dlcs") val dlcs: List<Long> = emptyList(),
