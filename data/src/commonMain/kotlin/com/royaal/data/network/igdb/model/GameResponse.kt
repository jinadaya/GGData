    @SerialName("expansions") val expansions: List<Long> = emptyList(),
    @SerialName("external_games") val externalGames: List<Long> = emptyList(),
    @SerialName("first_release_date") val firstReleaseDate: Long? = null,
    @SerialName("follows") val follows: Int? = null,
    @SerialName("forks") val forks: List<Long> = emptyList(),
